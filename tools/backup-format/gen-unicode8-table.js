/* eslint-env node */
// Generates the backup-password character table (Phase 6 spec v2.4 §4.1) from
// the Unicode Character Database 8.0.0:
//   node tools/backup-format/gen-unicode8-table.js <dir with UnicodeData.txt and DerivedAge.txt>
// Sources: https://www.unicode.org/Public/8.0.0/ucd/{UnicodeData,DerivedAge}.txt
// Output: android/app/src/main/java/com/trezor/app/backup/Unicode8Allowed.kt
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ALLOWED = new Set(
  'Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs'.split(
    ' ',
  ),
);
const EXTRA = [0x200c, 0x200d]; // ZWNJ, ZWJ (Cf, allowed by name)
const EXPECTED_SHA256 = {
  'UnicodeData.txt':
    '38b17e1118206489a7e0ab5d29d7932212d38838df7d3ec025ecb58e8798ec20',
  'DerivedAge.txt':
    '302f6d6171dc9c6165db86d0226b7923a64cea06c493d339d35436bf137606a3',
};
const OUT = path.join(
  __dirname,
  '../../android/app/src/main/java/com/trezor/app/backup/Unicode8Allowed.kt',
);

const dir = process.argv[2];
if (!dir) {
  throw new Error('usage: gen-unicode8-table.js <ucd-8.0.0-dir>');
}
const read = name => {
  const bytes = fs.readFileSync(path.join(dir, name));
  const sha = crypto.createHash('sha256').update(bytes).digest('hex');
  if (sha !== EXPECTED_SHA256[name]) {
    throw new Error(
      `${name}: SHA-256 ${sha} is not the recorded UCD 8.0.0 file`,
    );
  }
  return bytes.toString('utf8');
};

// General_Category per code point from UnicodeData.txt (ranges are First/Last pairs).
const category = new Map();
let first = null;
for (const line of read('UnicodeData.txt').split('\n')) {
  if (!line) {
    continue;
  }
  const f = line.split(';');
  const cp = parseInt(f[0], 16);
  if (f[1].endsWith(', First>')) {
    first = cp;
    continue;
  }
  if (f[1].endsWith(', Last>')) {
    for (let c = first; c <= cp; c++) {
      category.set(c, f[2]);
    }
    first = null;
    continue;
  }
  category.set(cp, f[2]);
}

// Age from DerivedAge.txt: the file for 8.0.0 lists every code point assigned
// in 8.0 or earlier (noncharacters, surrogates and private use included).
const aged = new Set();
for (const line of read('DerivedAge.txt').split('\n')) {
  const data = line.split('#')[0].trim();
  if (!data) {
    continue;
  }
  const [range, age] = data.split(';').map(s => s.trim());
  if (parseFloat(age) > 8.0) {
    throw new Error(`unexpected age ${age}`);
  }
  const [a, b] = range.split('..').map(s => parseInt(s, 16));
  for (let c = a; c <= (b ?? a); c++) {
    aged.add(c);
  }
}

const allowed = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const gc = category.get(cp) ?? 'Cn';
  const ok = aged.has(cp) && (ALLOWED.has(gc) || EXTRA.includes(cp));
  // Every code point with a UnicodeData category must have an age, and vice versa
  // except Cn noncharacters (in DerivedAge, absent from UnicodeData).
  if (category.has(cp) !== aged.has(cp) && !(aged.has(cp) && gc === 'Cn')) {
    throw new Error(
      `UnicodeData and DerivedAge disagree at U+${cp.toString(16)}`,
    );
  }
  if (ok) {
    allowed.push(cp);
  }
}

const ranges = [];
for (const cp of allowed) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) {
    last[1] = cp;
  } else {
    ranges.push([cp, cp]);
  }
}

const hex = n => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
const canonical =
  ranges.map(([a, b]) => `${a.toString(16)}-${b.toString(16)}`).join('\n') +
  '\n';
const tableSha = crypto.createHash('sha256').update(canonical).digest('hex');
const lines = [];
for (let i = 0; i < ranges.length; i += 4) {
  lines.push(
    '          ' +
      ranges
        .slice(i, i + 4)
        .map(([a, b]) => `${hex(a)}, ${hex(b)}`)
        .join(', ') +
      ',',
  );
}

const kotlin = `package com.trezor.app.backup

// GENERATED by tools/backup-format/gen-unicode8-table.js — do not edit.
// Source: Unicode Character Database 8.0.0
//   UnicodeData.txt SHA-256 ${EXPECTED_SHA256['UnicodeData.txt']}
//   DerivedAge.txt  SHA-256 ${EXPECTED_SHA256['DerivedAge.txt']}

/**
 * Code points a backup password may contain (Phase 6 spec v2.4 §4.1): Age ≤ 8.0 and
 * General_Category in {${[...ALLOWED].join(
   ' ',
 )}}, plus U+200C and U+200D. Sorted,
 * disjoint, inclusive [start, end] pairs.
 */
internal object Unicode8Allowed {

  /** SHA-256 of the ranges as "start-end\\n" lines in lowercase hex (${
    ranges.length
  } ranges, ${allowed.length} code points). */
  const val TABLE_SHA256 = "${tableSha}"

  const val CODE_POINTS = ${allowed.length}

  @JvmField
  val RANGES =
      intArrayOf(
${lines.join('\n')}
      )
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, kotlin);
console.log(
  `wrote ${path.relative(process.cwd(), OUT)}: ${ranges.length} ranges, ${
    allowed.length
  } code points, sha256 ${tableSha}`,
);
